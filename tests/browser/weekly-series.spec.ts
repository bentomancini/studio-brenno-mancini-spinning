import { test, expect } from '@playwright/test';

test('weekly classes are created atomically at the same local time; editing one does not change siblings', async ({ page, request }) => {
  const state = await (await request.get('http://127.0.0.1:3211/__test/state')).json() as { instructorId: string; bikeIds: string[] };
  await page.goto('/entrar');
  await page.getByLabel('E-mail', { exact: true }).fill('admin-ui@example.invalid');
  await page.getByLabel('Senha', { exact: true }).fill('test-browser-password-123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.setViewportSize({ width: 320, height: 800 });
  await page.goto('/admin/aulas/nova');
  const dialog = page.getByRole('dialog');
  const first = new Date(); first.setUTCHours(12, 0, 0, 0);
  first.setUTCDate(first.getUTCDate() + ((8 - first.getUTCDay()) % 7) + 14);
  const last = new Date(first); last.setUTCDate(last.getUTCDate() + 14);
  const title = 'TEST · Spinning semanal real';
  await dialog.getByLabel('Título').fill(title);
  await dialog.getByLabel('Instrutor').selectOption(state.instructorId);
  await dialog.getByLabel('Data de início').fill(first.toISOString().slice(0, 10));
  await dialog.getByLabel('Horário de início').fill('07:00');
  await dialog.getByLabel('Data de fim').fill(first.toISOString().slice(0, 10));
  await dialog.getByLabel('Horário de fim').fill('08:00');
  await dialog.getByRole('checkbox', { name: 'Repetir toda semana' }).check();
  await dialog.getByLabel('Repetir até').fill(last.toISOString().slice(0, 10));
  await dialog.getByLabel('Capacidade').fill('1');
  await dialog.getByLabel('Escolha de bicicleta').selectOption('required');
  await dialog.getByLabel('TEST-B01', { exact: true }).check();
  await dialog.getByLabel('Estado da aula').selectOption('published');
  await expect(dialog.getByRole('status').filter({ hasText: '3 aulas' })).toBeVisible();
  await dialog.getByRole('button', { name: 'Salvar aulas semanais' }).click();
  await expect(page).toHaveURL(/\/admin\/aulas\/[0-9a-f-]+$/);

  const response = await page.request.get(`/api/v1/admin/sessions?from=${encodeURIComponent(first.toISOString().slice(0, 10) + 'T00:00:00Z')}&to=${encodeURIComponent(new Date(last.getTime() + 2 * 86400000).toISOString().slice(0, 10) + 'T00:00:00Z')}&limit=100`);
  expect(response.status()).toBe(200);
  const sessions = ((await response.json()).data.items as Array<{ id: string; title: string; startsAt: string; sessionStatus: string; version: number }>).filter(item => item.title === title);
  expect(sessions).toHaveLength(3);
  expect(new Set(sessions.map(item => item.id)).size).toBe(3);
  expect(sessions.map(item => new Intl.DateTimeFormat('en-US', { timeZone: 'America/Sao_Paulo', weekday: 'long', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(new Date(item.startsAt)))).toEqual(['Monday 07:00', 'Monday 07:00', 'Monday 07:00']);
  expect(sessions.map(item => item.sessionStatus)).toEqual(['published', 'published', 'published']);
  await page.getByRole('button', { name: 'Editar aula' }).click();
  await expect(page.getByRole('dialog').getByRole('checkbox', { name: 'Repetir toda semana' })).toHaveCount(0);
  await page.getByRole('dialog').getByRole('button', { name: 'Descartar e fechar' }).click();
  const actor = (await (await page.request.get('/api/v1/session')).json()).data.userId as string;
  const cancelled = await page.request.delete(`/api/v1/admin/sessions/${sessions[0].id}`, { headers: { Origin: 'http://127.0.0.1:3210', 'X-Expected-Actor': actor, 'If-Match': `"${sessions[0].version}"` }, data: {} });
  expect(cancelled.status()).toBe(200);
  const sibling = await page.request.get(`/api/v1/admin/sessions/${sessions[1].id}`);
  expect((await sibling.json()).data.sessionStatus).toBe('published');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('a one-off class still creates a single occurrence from separate date and time fields', async ({ page, request }) => {
  const state = await (await request.get('http://127.0.0.1:3211/__test/state')).json() as { instructorId: string };
  await page.goto('/entrar');
  await page.getByLabel('E-mail', { exact: true }).fill('admin-ui@example.invalid');
  await page.getByLabel('Senha', { exact: true }).fill('test-browser-password-123');
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.setViewportSize({ width: 320, height: 800 });
  await page.goto('/admin/aulas/nova');
  const dialog = page.getByRole('dialog');
  const date = new Date(); date.setUTCDate(date.getUTCDate() + 21);
  await dialog.getByLabel('Título').fill('TEST · Aula avulsa com horários separados');
  await dialog.getByLabel('Instrutor').selectOption(state.instructorId);
  await dialog.getByLabel('Data de início').fill(date.toISOString().slice(0, 10));
  await dialog.getByLabel('Horário de início').fill('07:00');
  await dialog.getByLabel('Data de fim').fill(date.toISOString().slice(0, 10));
  await dialog.getByLabel('Horário de fim').fill('08:00');
  await dialog.getByLabel('Capacidade').fill('1');
  await dialog.getByLabel('Escolha de bicicleta').selectOption('none');
  await expect(dialog.getByRole('checkbox', { name: 'Repetir toda semana' })).not.toBeChecked();
  await dialog.getByRole('button', { name: 'Salvar aula', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/aulas\/[0-9a-f-]+$/);
  const response = await page.request.get(`/api/v1/admin/sessions/${page.url().split('/').at(-1)}`);
  expect(response.status()).toBe(200);
  const session = (await response.json()).data as { startsAt: string; endsAt: string; sessionStatus: string };
  const display = new Intl.DateTimeFormat('en-US', { timeZone: 'America/Sao_Paulo', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
  expect([display.format(new Date(session.startsAt)), display.format(new Date(session.endsAt))]).toEqual(['07:00', '08:00']);
  expect(session.sessionStatus).toBe('draft');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
